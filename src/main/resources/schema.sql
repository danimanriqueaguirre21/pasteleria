-- TABLA PEDIDO
CREATE TABLE IF NOT EXISTS pedido (
    id_pedido INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL,
    fecha_pedido TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_entrega TIMESTAMP,
    direccion_entrega VARCHAR(255) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    total DECIMAL(10,2) NOT NULL CHECK (total > 0),
    estado VARCHAR(30) DEFAULT 'RECIBIDO',
    medio_pago VARCHAR(30),
    id_repartidor INT,
    codigo_seguimiento VARCHAR(40),

    CONSTRAINT fk_pedido_usuario
    FOREIGN KEY (id_usuario)
    REFERENCES usuario(id_usuario),

    CONSTRAINT fk_pedido_repartidor
    FOREIGN KEY (id_repartidor)
    REFERENCES usuario(id_usuario)
);

-- Si la base ya existia, estas columnas no se crean solas.
ALTER TABLE pedido ADD COLUMN IF NOT EXISTS fecha_entrega TIMESTAMP;
ALTER TABLE pedido ADD COLUMN IF NOT EXISTS medio_pago VARCHAR(30);
ALTER TABLE pedido ADD COLUMN IF NOT EXISTS id_repartidor INT;
ALTER TABLE pedido ADD COLUMN IF NOT EXISTS codigo_seguimiento VARCHAR(40);

UPDATE pedido
SET id_repartidor = NULL
WHERE id_repartidor IS NOT NULL
  AND id_repartidor NOT IN (SELECT id_usuario FROM usuario);

ALTER TABLE pedido ADD CONSTRAINT IF NOT EXISTS fk_pedido_repartidor
    FOREIGN KEY (id_repartidor) REFERENCES usuario(id_usuario);

-- TABLA DETALLE PEDIDO
CREATE TABLE IF NOT EXISTS detalle_pedido (
    id_detalle INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INT NOT NULL,
    id_producto INT NOT NULL,
    cantidad INT NOT NULL CHECK (cantidad > 0),
    precio_unitario DECIMAL(10,2) NOT NULL CHECK (precio_unitario > 0),
    subtotal DECIMAL(10,2) NOT NULL CHECK (subtotal > 0),

    CONSTRAINT fk_detalle_pedido
    FOREIGN KEY (id_pedido)
    REFERENCES pedido(id_pedido),

    CONSTRAINT fk_detalle_producto
    FOREIGN KEY (id_producto)
    REFERENCES producto(id_producto)
);

