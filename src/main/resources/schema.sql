        st.execute("ALTER TABLE usuario ADD CONSTRAINT IF NOT EXISTS chk_usuario_rol CHECK (rol IN (''ADMINISTRADOR'', ''CLIENTE'', ''CAJERO'', ''REPARTIDOR''))");
